from dataclasses import dataclass, field, asdict
from typing import List, Optional
from app.models.span_record import SpanRecord


@dataclass
class RequestRecord:
    """
    Represents one complete agent request after parsing.

    This is the shared request-level data model used
    across the evaluation pipeline.
    """

    trace_id: str
    request_id: str
    timestamp: str

    agent_name: str

    prompt: str

    tool_calls: List[str] = field(default_factory=list)

    retries: int = 0

    latency_ms: float = 0.0

    status: str = "UNKNOWN"

    error: Optional[str] = None

    # Actual response generated by the agent
    actual_result: Optional[str] = None

    failure_type: Optional[str] = None

    # Threading & Waterfall Spans
    thread_id: str = ""
    spans: List[SpanRecord] = field(default_factory=list)

    def to_dict(self):
        d = asdict(self)
        d['spans'] = [s.to_dict() if hasattr(s, 'to_dict') else s for s in self.spans]
        return d